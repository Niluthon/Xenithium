// xenithium-bench-embed: writes the benchmark corpus into a C++ source file, so the tool is one binary.
// xenithium-bench-embed CORPUS_DIR OUT.cpp
// CORPUS_DIR holds <set>/<kind>/<file> (set = "engine", "generic"; kind = "code", "prose"...). The output defines
// embedded:kFiles (corpus.hpp), in path order so a set's hash does not depend on the file system's listing order.
// Build-time only.
#include <algorithm>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <iterator>
#include <string>
#include <vector>

namespace fs = std::filesystem;

namespace {

constexpr int kBytesPerLine = 32;

struct Entry {
  std::string set, kind, name;
  fs::path path;
};

std::vector<Entry> list_corpus(const fs::path &dir) {
  std::vector<Entry> entries;
  for (const auto &set : fs::directory_iterator(dir)) {
    if (!set.is_directory()) continue;
    for (const auto &kind : fs::directory_iterator(set.path())) {
      if (!kind.is_directory()) continue;
      for (const auto &file : fs::directory_iterator(kind.path()))
        if (file.is_regular_file())
          entries.push_back({set.path().filename().string(), kind.path().filename().string(), file.path().filename().string(), file.path()});
    }
  }
  std::ranges::sort(entries, {}, [](const Entry &e) { return e.set + "/" + e.kind + "/" + e.name; });
  return entries;
}

void write_bytes(std::ofstream &out, const std::string &bytes) {
  for (size_t i = 0; i < bytes.size(); ++i) {
    out << static_cast<unsigned>(static_cast<unsigned char>(bytes[i])) << ',';
    if ((i + 1) % kBytesPerLine == 0) out << '\n';
  }
}

}  // namespace

int main(int argc, char **argv) {
  if (argc != 3) {
    std::fprintf(stderr, "usage: xenithium-bench-embed CORPUS_DIR OUT.cpp\n");
    return 2;
  }
  const std::vector<Entry> entries = list_corpus(argv[1]);
  if (entries.empty()) {
    std::fprintf(stderr, "xenithium-bench-embed: no <set>/<kind>/<file> under %s\n", argv[1]);
    return 1;
  }
  std::ofstream out(argv[2], std::ios::binary);
  out << "// Generated by xenithium-bench-embed from tools/bench/corpus: do not edit.\n#include \"corpus.hpp\"\n\nnamespace {\n";
  std::vector<size_t> sizes;
  for (size_t i = 0; i < entries.size(); ++i) {
    std::ifstream in(entries[i].path, std::ios::binary);
    const std::string bytes((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
    sizes.push_back(bytes.size());
    out << "const unsigned char kData" << i << "[] = {\n";
    write_bytes(out, bytes);
    out << "0};\n";  // one spare byte: an empty file is still a valid array
  }
  out << "}  // namespace\n\nnamespace xenithium::bench::embedded {\nconst File kFiles[] = {\n";
  for (size_t i = 0; i < entries.size(); ++i)
    out << "    {\"" << entries[i].set << "\", \"" << entries[i].kind << "\", \"" << entries[i].name << "\", kData" << i << ", " << sizes[i] << "},\n";
  out << "};\nconst std::size_t kFileCount = " << entries.size() << ";\n}  // namespace xenithium::bench::embedded\n";
  if (!out.good()) {
    std::fprintf(stderr, "xenithium-bench-embed: cannot write %s\n", argv[2]);
    return 1;
  }
  return 0;
}
