void test_image() {
  const auto colors = b::grid_colors();
  std::vector<b::Rgb> cells;
  for (size_t i = 0; i < 9; ++i) cells.push_back(colors[i % colors.size()].rgb);
  // sides whose row lengths cross the run-length code's group borders, and one large picture
  bool round_trips = true;
  size_t large_bytes = 0;
  for (const int side : {9, 31, 200, 448, 1344}) {
    const b::Image image = b::grid_image(side, 3, cells);
    const std::string png = b::png_of(image);
    xenithium::util::RawImage decoded;
    std::string err;
    const bool ok = xenithium::util::decode_png(reinterpret_cast<const uint8_t *>(png.data()), png.size(), decoded, err);
    round_trips &= ok && decoded.w == side && decoded.h == side && decoded.px.size() == image.pixels.size() * static_cast<size_t>(decoded.channels);
    if (!ok) std::printf("  decode_png %d px: %s\n", side, err.c_str());
    for (size_t p = 0; round_trips && p < image.pixels.size(); ++p) {
      const uint8_t *px = decoded.px.data() + p * static_cast<size_t>(decoded.channels);
      round_trips &= b::Rgb{px[0], px[1], px[2]} == image.pixels[p];
    }
    if (side == 1344) large_bytes = png.size();
  }
  CHECK(round_trips, "image: the PNGs decode to the same pixels with the engine's decoder at five sizes");
  CHECK(large_bytes > 0 && large_bytes < 128 * 1024, "image: a 1,344-pixel grid picture (5.4 MB of pixels) is %zu bytes as a PNG: runs are coded as matches", large_bytes);
  const b::Image image = b::grid_image(300, 3, cells);
  CHECK(image.pixels[50 * 300 + 50] == colors[0].rgb && image.pixels[250 * 300 + 150] == colors[7 % colors.size()].rgb && image.pixels[0] != colors[0].rgb,
        "image: cell (0,0) and cell (2,1) carry their colours; the corner is ground");
  std::string bytes, err;
  CHECK(xenithium::util::parse_data_url(b::png_data_url(image), bytes, err) && bytes == b::png_of(image), "image: the data URL carries the PNG (%s)", err.c_str());
}

void test_quality() {
  std::set<std::string_view> ids;
  bool own_answers = true;
  for (const b::QualityItem &item : b::quality_items()) {
    ids.insert(item.id);
    own_answers &= b::is_correct(item.kind, item.answer, b::answer_of("Working it out.\nANSWER: " + std::string(item.answer)));
  }
  CHECK(ids.size() == b::quality_items().size() && b::quality_items().size() == 30 && own_answers, "quality: 30 items with unique ids, each graded correct on its own answer");
  CHECK(b::answer_of("x\nAnswer: **60 km/h**.\n") == "60 km/h" && b::answer_of("ANSWER: 1\nno, wait\nANSWER: `Dan`") == "Dan" && b::answer_of("no line here").empty(),
        "quality: the answer is what follows the last ANSWER:, without emphasis marks and the final period");
  using K = b::AnswerKind;
  CHECK(b::is_correct(K::number, "60", "60 km/h") && b::is_correct(K::number, "820", "820.0") && b::is_correct(K::number, "1234", "1,234") && !b::is_correct(K::number, "6", "60") &&
            !b::is_correct(K::number, "5", "0.05") && !b::is_correct(K::number, "5", "five"),
        "quality: a number answer is the first number of the reply");
  CHECK(b::is_correct(K::words, "Ilse Brandt", "Foreman Ilse Brandt.") && b::is_correct(K::words, "apple banana fig pear", "apple, banana, fig, pear") &&
            b::is_correct(K::words, "no", "No") && !b::is_correct(K::words, "no", "not known") && !b::is_correct(K::words, "Dan", "Daniel"),
        "quality: a words answer is the expected words in order, whole words only");
  CHECK(b::is_correct(K::exact, "TUNED TO THE LAST BYTE", "TUNED TO THE LAST BYTE") && !b::is_correct(K::exact, "TUNED TO THE LAST BYTE", "Tuned to the last byte") &&
            b::is_correct(K::exact, "ff", "ff") && !b::is_correct(K::exact, "ff", "0xff"),
        "quality: an exact answer matches character for character");
}

