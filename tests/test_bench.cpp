// ---- the stream decoders ----

std::string decode_split(const std::string &response, size_t piece, int *status = nullptr, bool *done = nullptr) {
  b::HttpResponseDecoder http;
  std::string body;
  for (size_t at = 0; at < response.size(); at += piece) http.feed(response.substr(at, piece), body);
  if (status) *status = http.status();
  if (done) *done = http.done();
  return body;
}

void test_http_decoder() {
  const std::string chunked = "HTTP/1.1 200 OK\r\nContent-Type: text/event-stream\r\nTransfer-Encoding: chunked\r\n\r\n5\r\nhello\r\n1;ext=1\r\n \r\n6\r\nworld!\r\n0\r\n\r\n";
  const std::string sized = "HTTP/1.1 404 Not Found\r\ncontent-length: 9\r\n\r\nnot here!";
  const std::string to_close = "HTTP/1.0 200 OK\r\nServer: x\r\n\r\nuntil the peer closes";
  bool every_split = true;
  for (size_t piece = 1; piece <= chunked.size(); ++piece) {
    int status = 0;
    bool done = false;
    every_split &= decode_split(chunked, piece, &status, &done) == "hello world!" && status == 200 && done;
    every_split &= decode_split(sized, piece, &status, &done) == "not here!" && status == 404 && done;
    every_split &= decode_split(to_close, piece, &status, &done) == "until the peer closes" && status == 200 && !done;
  }
  CHECK(every_split, "http decoder: chunked, Content-Length and to-close bodies at every split size");
  b::HttpResponseDecoder bad;
  std::string body;
  CHECK(!bad.feed("SSH-2.0-OpenSSH\r\n\r\n", body) && !bad.error().empty(), "http decoder: a non-HTTP reply is refused with a reason");
}

void test_sse() {
  const std::string stream = ": comment\r\n\r\ndata: {\"a\":1}\r\n\r\nevent: x\ndata: line one\ndata: line two\n\ndata:[DONE]\n\n";
  bool every_split = true;
  for (size_t piece = 1; piece <= stream.size(); ++piece) {
    b::SseSplitter sse;
    std::vector<std::string> events;
    for (size_t at = 0; at < stream.size(); at += piece) sse.feed(stream.substr(at, piece), [&](std::string_view data) { events.emplace_back(data); });
    every_split &= events == std::vector<std::string>{"{\"a\":1}", "line one\nline two", "[DONE]"};
  }
  CHECK(every_split, "sse: events with CRLF, a comment, another field and two data lines, at every split size");
}

