void test_corpus() {
  const b::Corpus corpus = b::Corpus::from_embedded();
  CHECK(b::corpus_sets().size() == 2 && b::corpus_sets()[0].name == "hard" && b::find_corpus_set("medium") && !b::find_corpus_set("easy") &&
            b::Corpus::from_embedded("hard").hash() == corpus.hash() && b::Corpus::from_embedded("easy").kinds().empty(),
        "corpus: two embedded sets, hard the default; an unknown set is empty");
  const b::Corpus medium = b::Corpus::from_embedded("medium");
  CHECK(medium.kinds() == std::vector<std::string>({"code", "prose"}) && medium.chars("code") > 1'000'000 && medium.chars("prose") > 300'000,
        "corpus: the medium set has over 1 MB of code and 300 KB of prose (%zu, %zu)", medium.chars("code"), medium.chars("prose"));
  CHECK(medium.hash() == kMediumCorpusHashV1, "corpus: medium hash %s is the pinned one of version %d (a file changed? bump both)", medium.hash().c_str(),
        b::kMediumCorpusVersion);
  CHECK(medium.document("code", 30'000).text.rfind("### 01-models.py\n```\n", 0) == 0 && !medium.document("prose", 150'000).wrapped,
        "corpus: a medium document starts at its first file; 150,000 characters of prose do not repeat");
  const auto kinds = corpus.kinds();
  CHECK(kinds == std::vector<std::string>({"code", "prose"}), "corpus: kinds code and prose");
  CHECK(corpus.chars("code") > 1'000'000 && corpus.chars("prose") > 100'000, "corpus: over 1 MB of code and 100 KB of prose (%zu, %zu)", corpus.chars("code"), corpus.chars("prose"));
  CHECK(corpus.hash() == kCorpusHashV1, "corpus: hash %s is the pinned one of version %d (a corpus file changed? bump both)", corpus.hash().c_str(), b::kCorpusVersion);
  const auto doc = corpus.document("code", 50'000);
  CHECK(doc.text.size() >= 50'000 && doc.text.size() < 50'200 && !doc.wrapped && doc.text.rfind("### 01-batch_engine.cpp\n```\n", 0) == 0 && doc.text.ends_with("\n```\n\n"),
        "corpus: a 50,000-character document starts at the first file under its name and closes its fence (%zu characters)", doc.text.size());
  const auto later = corpus.document("code", 50'000, 3);
  CHECK(later.text.rfind("### 04-tokenizer.cpp\n", 0) == 0 && later.text != doc.text, "corpus: first_file starts the document at another file");
  CHECK(corpus.document("prose", 400'000).wrapped && corpus.document("none", 1000).text.empty(), "corpus: a kind shorter than asked repeats and says so; an unknown kind is empty");
  // a document is valid UTF-8 at every length (a cut inside a line must not split a character: a server
  // refuses such a request, "Invalid JSON: invalid UTF-8")
  auto utf8_ok = [](std::string_view t) {
    for (size_t i = 0; i < t.size();) {
      const auto c = static_cast<unsigned char>(t[i]);
      const size_t n = c < 0x80 ? 1 : (c >> 5) == 6 ? 2 : (c >> 4) == 14 ? 3 : (c >> 3) == 30 ? 4 : 0;
      if (n == 0 || i + n > t.size()) return false;
      for (size_t j = 1; j < n; ++j)
        if ((static_cast<unsigned char>(t[i + j]) & 0xC0) != 0x80) return false;
      i += n;
    }
    return true;
  };
  size_t bad = 0, tried = 0;
  for (const b::Corpus *c : {&corpus, &medium})
    for (const char *kind : {"code", "prose"})
      for (size_t chars = 1; chars < 160'000; chars += 37, ++tried) bad += !utf8_ok(c->document(kind, chars, chars % 7).text);
  CHECK(bad == 0, "corpus: every document is valid UTF-8 (%zu of %zu lengths cut a character)", bad, tried);
  std::set<std::string_view> ids, categories;
  for (const b::ShortPrompt &p : b::short_prompts()) ids.insert(p.id), categories.insert(p.category);
  bool mixes_whole = !b::weight_mixes().empty() && b::weight_mixes()[0].id == "agent" && b::category_weights().data() == b::weight_mixes()[0].weights.data();
  for (const b::WeightMix &mix : b::weight_mixes()) {
    double weight = 0;
    std::set<std::string_view> weighted;
    for (const b::CategoryWeight &w : mix.weights) weight += w.weight, weighted.insert(w.category), mixes_whole &= w.weight >= 0;
    mixes_whole &= weighted == categories && mix.weights.size() == categories.size() && std::abs(weight - 1) < 1e-9;
  }
  CHECK(ids.size() == b::short_prompts().size() && mixes_whole, "prompts: unique ids; every mix weighs every category once and sums to 1, the agent mix first and the default");
  // the mix's rate is the harmonic mean: half the tokens at 300 tok/s and half at 100 take 1/600 + 1/200 s per token
  const std::vector<std::pair<std::string, double>> halves = {{"code", 0.5}, {"prose", 0.5}, {"math", 0.0}};
  const b::MixRate both = b::mix_rate(halves, {{"code", 300.0}, {"prose", 100.0}, {"math", 50.0}}), one = b::mix_rate(halves, {{"code", 300.0}});
  CHECK(std::abs(both.tps - 150) < 1e-9 && std::abs(both.covered - 1) < 1e-12 && std::abs(one.tps - 300) < 1e-9 && std::abs(one.covered - 0.5) < 1e-12 &&
            b::mix_rate(halves, {}).tps == 0,
        "mix: 50 / 50 of 300 and 100 tok/s comes out at 150 (not 200); a weight of 0 counts nothing; a missing kind leaves its share uncovered");
  CHECK(!throws_invalid([] { (void)b::make_plan("", "decode", {"decode.weights=even"}); }) && !throws_invalid([] { (void)b::make_plan("", "decode", {"decode.weights=code:1,prose:3"}); }) &&
            throws_invalid([] { (void)b::make_plan("", "decode", {"decode.weights=fast"}); }) && throws_invalid([] { (void)b::make_plan("", "decode", {"decode.weights=code:x"}); }) &&
            throws_invalid([] { (void)b::make_plan("", "decode", {"decode.weights=poetry:1"}); }) && throws_invalid([] { (void)b::make_plan("", "decode", {"decode.weights=code:0"}); }),
        "plan: decode.weights takes a mix or category:share,...; an unknown name, category or share is refused before anything is sent");
  // long-agents walks the list with a stride of three to change category every task
  bool three_in_a_row = b::short_prompts().size() % 3 == 0;
  for (size_t i = 0; three_in_a_row && i < b::short_prompts().size(); i += 3)
    three_in_a_row = b::short_prompts()[i].category == b::short_prompts()[i + 1].category && b::short_prompts()[i].category == b::short_prompts()[i + 2].category &&
                     (i == 0 || b::short_prompts()[i].category != b::short_prompts()[i - 1].category);
  CHECK(three_in_a_row && categories.count("math") == 1 && categories.size() == 8, "prompts: eight categories with maths among them, three prompts each in a row");

  // the easy set: the same eight categories, four prompts each in a row, unique ids; a chat prompt goes on from an
  // exchange that ends with the assistant's turn
  const auto easy = b::short_prompts(b::PromptSet::easy);
  std::set<std::string_view> easy_ids, easy_categories;
  bool four_in_a_row = easy.size() == 4 * categories.size(), chats_go_on = true;
  for (size_t i = 0; i < easy.size(); ++i) {
    easy_ids.insert(easy[i].id), easy_categories.insert(easy[i].category);
    four_in_a_row &= easy[i].category == easy[i - i % 4].category && (i % 4 != 0 || i == 0 || easy[i].category != easy[i - 1].category);
    if (easy[i].category == "chat") chats_go_on &= easy[i].earlier.size() >= 2 && easy[i].earlier.back().role == "assistant";
    else chats_go_on &= easy[i].earlier.empty();
  }
  CHECK(four_in_a_row && easy_ids.size() == easy.size() && easy_categories == categories && chats_go_on && b::short_prompts().data() == b::short_prompts(b::PromptSet::standard).data(),
        "prompts: the easy set has the eight categories, four prompts each in a row, unique ids; its chats go on from an exchange");
  const auto easy_mix = std::ranges::find(b::weight_mixes(), std::string_view("easy"), &b::WeightMix::id);
  const b::MixRate plain = b::mix_rate(halves, {{"code", 300.0}, {"prose", 100.0}}, b::MixAverage::arithmetic);
  CHECK(easy_mix != b::weight_mixes().end() && easy_mix->average == b::MixAverage::arithmetic && std::abs(plain.tps - 200) < 1e-9 && std::abs(plain.covered - 1) < 1e-12 &&
            b::mix_rate(halves, {{"code", 300.0}}, b::MixAverage::arithmetic).tps == 300,
        "mix: the easy mix is the weighted mean - 50 / 50 of 300 and 100 tok/s reads 200; over the kinds that ran");
}

