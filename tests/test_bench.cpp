// ---- end to end against a local OpenAI-style server ----

// Answers GET /v1/models and streams POST /v1/chat/completions: a role chunk, then kUpdates updates of two tokens
// each, then the usage. Refuses a request that carries "top_k" (an endpoint without that extension) and an unknown model.
// A request with tools gets a streamed call of get_weather (its name, then its arguments in two pieces); a request
// that carries a tool's result is answered with "14 " per update.
class FakeEndpoint {
 public:
  static constexpr int kUpdates = 5, kTokensPerUpdate = 2;
  static constexpr std::string_view kCallArguments = R"({"city":"Munich","unit":"celsius"})";

  FakeEndpoint() {
    listen_fd_ = ::socket(AF_INET, SOCK_STREAM, 0);
    const int one = 1;
    ::setsockopt(listen_fd_, SOL_SOCKET, SO_REUSEADDR, &one, sizeof(one));
    sockaddr_in addr{};
    addr.sin_family = AF_INET;
    addr.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
    ::bind(listen_fd_, reinterpret_cast<sockaddr *>(&addr), sizeof(addr));
    ::listen(listen_fd_, 64);
    socklen_t len = sizeof(addr);
    ::getsockname(listen_fd_, reinterpret_cast<sockaddr *>(&addr), &len);
    port_ = ntohs(addr.sin_port);
    acceptor_ = std::jthread([this] { accept_loop(); });
  }
  ~FakeEndpoint() {
    stopping_ = true;
    ::shutdown(listen_fd_, SHUT_RDWR);
    ::close(listen_fd_);
  }
  std::string url() const { return "http://127.0.0.1:" + std::to_string(port_) + "/v1"; }
  int chats() const { return chats_; }
  int image_chats() const { return image_chats_; }
  std::atomic<bool> refuse_images{false};  // answer a request that carries a picture with a 400, as a text-only endpoint does
  std::atomic<int> update_delay_ms{2};  // before every update: a slower stream for a client that abandons it

 private:
  void accept_loop() {
    while (!stopping_) {
      const int fd = ::accept(listen_fd_, nullptr, nullptr);
      if (fd < 0) break;
      std::thread([this, fd] { serve(fd); }).detach();
    }
  }

  static std::string read_request(int fd) {
    std::string request;
    char buf[65536];
    size_t body_at = std::string::npos, body_len = 0;
    while (body_at == std::string::npos || request.size() < body_at + body_len) {
      const ssize_t n = ::recv(fd, buf, sizeof(buf), 0);
      if (n <= 0) break;
      request.append(buf, static_cast<size_t>(n));
      if (body_at == std::string::npos)
        if (const size_t end = request.find("\r\n\r\n"); end != std::string::npos) {
          body_at = end + 4;
          if (const size_t cl = request.find("Content-Length: "); cl != std::string::npos && cl < end) body_len = std::stoul(request.substr(cl + 16));
        }
    }
    return request;
  }

  static void send_all(int fd, const std::string &bytes) { (void)::send(fd, bytes.data(), bytes.size(), MSG_NOSIGNAL); }
  static void send_chunk(int fd, const std::string &event) {
    const std::string data = "data: " + event + "\n\n";
    char size[16];
    std::snprintf(size, sizeof(size), "%zx\r\n", data.size());
    send_all(fd, size + data + "\r\n");
  }
  static void send_plain(int fd, int status, const std::string &body) {
    send_all(fd, "HTTP/1.1 " + std::to_string(status) + " X\r\nContent-Length: " + std::to_string(body.size()) + "\r\nConnection: close\r\n\r\n" + body);
  }

  void serve(int fd) {
    const std::string request = read_request(fd);
    if (request.rfind("GET /v1/models", 0) == 0) send_plain(fd, 200, R"({"object":"list","data":[{"id":"fake-model","max_model_len":8192,"kv_pool_tokens":40000,"tensor_parallel":1,"devices":[{"name":"Card A","memory_bytes":1073741824,"memory_gb":1,"pci":"0000:03:00.0"}]},{"id":"other-listed","max_model_len":4096}]})");
    else if (request.rfind("POST /v1/chat/completions", 0) != 0) send_plain(fd, 404, "{}");
    else if (request.find("\"top_k\"") != std::string::npos) send_plain(fd, 400, R"({"error":{"message":"unknown field top_k"}})");
    else if (refuse_images && request.find("\"image_url\"") != std::string::npos) send_plain(fd, 400, R"({"error":{"message":"image input is off on this server"}})");
    else if (request.find("\"fake-model\"") == std::string::npos) send_plain(fd, 404, R"({"error":{"message":"no such model"}})");
    else {
      ++chats_;
      if (request.find("data:image/png;base64,") != std::string::npos) ++image_chats_;
      send_all(fd, "HTTP/1.1 200 OK\r\nContent-Type: text/event-stream\r\nTransfer-Encoding: chunked\r\n\r\n");
      send_chunk(fd, R"({"choices":[{"index":0,"delta":{"role":"assistant","content":""}}]})");
      const bool calls = request.find("\"tools\"") != std::string::npos && request.find("\"role\":\"tool\"") == std::string::npos;
      if (calls) stream_call(fd);
      else
        for (int i = 0; i < kUpdates; ++i) {
          std::this_thread::sleep_for(std::chrono::milliseconds(update_delay_ms.load()));
          send_chunk(fd, request.find("\"role\":\"tool\"") != std::string::npos ? R"({"choices":[{"index":0,"delta":{"content":"14 "}}]})"
                                                                                  : R"({"choices":[{"index":0,"delta":{"content":"ab "}}]})");
        }
      send_chunk(fd, calls ? R"({"choices":[{"index":0,"delta":{},"finish_reason":"tool_calls"}]})" : R"({"choices":[{"index":0,"delta":{},"finish_reason":"length"}]})");
      const int prompt_tokens = static_cast<int>(request.size() / 4);
      send_chunk(fd, R"({"choices":[],"usage":{"prompt_tokens":)" + std::to_string(prompt_tokens) + R"(,"completion_tokens":)" + std::to_string(kUpdates * kTokensPerUpdate) +
                         R"(,"prompt_tokens_details":{"cached_tokens":3}}})");
      send_chunk(fd, "[DONE]");
      send_all(fd, "0\r\n\r\n");
    }
    ::close(fd);
  }

  // A call of get_weather as servers stream one: its id and name first, then the arguments in two pieces.
  void stream_call(int fd) const {
    send_chunk(fd, R"({"choices":[{"index":0,"delta":{"tool_calls":[{"index":0,"id":"call_7","type":"function","function":{"name":"get_weather","arguments":""}}]}}]})");
    const size_t half = kCallArguments.size() / 2;
    for (const std::string_view piece : {kCallArguments.substr(0, half), kCallArguments.substr(half)}) {
      std::this_thread::sleep_for(std::chrono::milliseconds(update_delay_ms.load()));
      std::string arguments;
      xenithium::json::write_string(piece, arguments);
      send_chunk(fd, R"({"choices":[{"index":0,"delta":{"tool_calls":[{"index":0,"function":{"arguments":)" + arguments + "}}]}}]}");
    }
  }

  int listen_fd_ = -1;
  int port_ = 0;
  std::atomic<bool> stopping_{false};
  std::atomic<int> chats_{0}, image_chats_{0};
  std::jthread acceptor_;
};

